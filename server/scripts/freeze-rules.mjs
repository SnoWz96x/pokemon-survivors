// Freezes the previous rules' simulator for the API (`npm run rules:freeze`, see server/sims/README.md).
//
// With RULES_VERSION at N in the working tree, it finds the code as it was at N-1, bundles its
// simulation into one self-contained ESM file, server/sims/rules-<N-1>.mjs, and drops any other.
// The API loads it only to judge a run that straddled a rules deploy (server/src/sims.ts).
//
// Which commit plays N-1, first that holds it:
//   1. HEAD, when the bump isn't committed yet;
//   2. origin/main, when HEAD sits on it (a rebased branch): what production runs;
//   3. the first parent of the commit where N landed on HEAD's first-parent history.
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = fileURLToPath(new URL('../..', import.meta.url))
const simsDir = fileURLToPath(new URL('../sims/', import.meta.url))
const REPLAY = 'src/game/replay.ts'

const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim()
const tryGit = (...args) => {
  try {
    return git(...args)
  } catch {
    return null
  }
}

const versionIn = (source) => {
  const m = /export const RULES_VERSION = (\d+)/.exec(source ?? '')
  return m ? Number(m[1]) : null
}
const versionAt = (commit) => versionIn(tryGit('show', `${commit}:${REPLAY}`))

const current = versionIn(readFileSync(join(root, REPLAY), 'utf8'))
if (current === null) throw new Error(`no RULES_VERSION in ${REPLAY}`)
const target = current - 1

const findCommit = () => {
  if (versionAt('HEAD') === target) return git('rev-parse', 'HEAD')
  const main = tryGit('rev-parse', '--verify', '-q', 'origin/main')
  if (main && tryGit('merge-base', '--is-ancestor', main, 'HEAD') !== null && versionAt(main) === target) return main
  // Newest first: the last commit still at N or above is where N landed.
  let landing = null
  for (const commit of git('rev-list', '--first-parent', 'HEAD', '--', REPLAY).split('\n').filter(Boolean)) {
    const v = versionAt(commit)
    if (v === null || v < current) break
    landing = commit
  }
  const before = landing && tryGit('rev-parse', '--verify', '-q', `${landing}^1`)
  if (!before || versionAt(before) !== target) {
    throw new Error(`no commit on HEAD's first-parent history plays rules ${target} (rules ${current} landed in ${landing ?? 'none'}, on top of rules ${before ? versionAt(before) : 'none'})`)
  }
  return before
}

const commit = findCommit()
const about = git('log', '-1', '--format=%h %cs %s', commit)
const out = join(simsDir, `rules-${target}.mjs`)
const tree = mkdtempSync(join(tmpdir(), `rules-${target}-`))

// What the API needs of a simulator (`Sim` in server/src/sims.ts).
const ENTRY = `
export { RULES_VERSION, parseReplay, resimulate } from './src/game/replay'
export { outbreakFits } from './src/game/outbreak'
export { halloweenFits } from './src/game/halloween'
`

try {
  git('worktree', 'add', '--detach', tree, commit)
  const bundled = await build({
    stdin: { contents: ENTRY, resolveDir: tree, loader: 'ts', sourcefile: 'frozen-entry.ts' },
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'neutral',
    target: 'node24',
    minify: true,
    legalComments: 'none',
    logLevel: 'warning',
  })
  const header = [
    `// GENERATED by \`npm run rules:freeze\` (server/scripts/freeze-rules.mjs): do not edit.`,
    `// The game's simulation at RULES_VERSION ${target}, bundled from commit ${about}.`,
    `// The API re-simulates runs that straddled the rules ${target} -> ${current} deploy with it (server/sims/README.md).`,
    '',
  ].join('\n')
  for (const f of readdirSync(simsDir).filter((f) => /^rules-\d+\.mjs$/.test(f))) rmSync(join(simsDir, f))
  writeFileSync(out, header + bundled.outputFiles[0].text)
  const frozen = await import(`${out}?t=${Date.now()}`)
  if (frozen.RULES_VERSION !== target) throw new Error(`the bundle says rules ${frozen.RULES_VERSION}, expected ${target}`)
  console.log(`froze rules ${target} from ${about}\n  -> server/sims/rules-${target}.mjs (${(bundled.outputFiles[0].contents.length / 1024).toFixed(0)} KB)`)
} finally {
  tryGit('worktree', 'remove', '--force', tree)
  rmSync(tree, { recursive: true, force: true })
}
